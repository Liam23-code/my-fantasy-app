# Betting Engine: offline, deterministic fair-line analysis across five
# sections -- Player Props, Money Lines, Parlays, Player Comparison, and
# Cross-Sport Parlay -- for both NFL and NBA.
#
# Odds come from exactly two places, both offline, per sport: our own
# default file (generated by our own projection/team models) and an
# optional file you upload here (CSV, JSON, or delimited text), which
# overrides matching entries and leaves everything else untouched. Nothing
# on this page ever fetches a sportsbook, and nothing here places a bet --
# every number is a side-by-side comparison of our fair line against odds
# you supplied.
#
# NFL and NBA share this page's UI and the same underlying contract
# (default file + upload, real per-game rates, disclosed "basis" on every
# generated line) but are evaluated by separate, sport-specific modules --
# see architecture.md / betting_engine.md for why the two engines aren't
# merged into one codebase. NFL: fantasy_engine/betting/*. NBA: modules/nba_*.py.
#
# Performance notes (see performance_notes.md): every real-data loader used
# here is TTL-cached at the module level (modules/nba_schedule.py,
# modules/nba_props_loader.py, modules/nba_odds_loader.py,
# betting/odds_loader.py, betting/team_model.py), so the page-level
# @st.cache_data below is a second, Streamlit-specific layer on top of an
# already-cached call, not the only caching in play. Each sport's props/
# money-lines/parlays evaluation is computed once per render and reused
# across tabs (previously this page called evaluate_props/
# price_aware_evaluations a second time inside the Parlays tab).

