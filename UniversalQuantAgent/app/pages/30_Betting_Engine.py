def _parlay_builder(*, prop_evaluations: list[dict[str, Any]], sport_key: str, empty_icon: str) -> None:
    """Shared parlay-builder UX for one sport: quick-add top edges, leg summary, evaluation. NFL and NBA render identically here."""
    if sport_key == "NFL":
        options = {f"{row['name']} {row['market']} {row['recommended_side']} {row['line']}": row for row in prop_evaluations}
        side_key, edge_key, price_prefix = "recommended_side", "recommended_edge", ""
    else:
        options = {f"{row['player']} {row['category']} {row['recommended_priced_side']} {row['sportsbook_line']}": row for row in prop_evaluations}
        side_key, edge_key, price_prefix = "recommended_priced_side", "recommended_priced_ev", ""

    if len(options) < 2:
        empty_state("Not enough props loaded to build a parlay", "A parlay needs at least two legs -- load more props first.", icon=empty_icon)
        return

    ranked_labels = sorted(options, key=lambda label: -abs(options[label][edge_key]))
    picker_key = f"{sport_key}_parlay_leg_picker"
    # Streamlit forbids passing both `default=` and pre-setting session_state
    # for the same widget key -- seed/reseed session_state here instead and
    # let the widget read purely from it, so the Quick-add button's
    # session_state write below never conflicts with a `default=`. Reseed
    # (not just seed-once) whenever the stored selection contains a label
    # that's no longer in the current options (e.g. after a new upload
    # changes the available props) -- an empty selection is always valid,
    # but a stale one would make the widget itself raise.
    stored = st.session_state.get(picker_key)
    if stored is None or any(label not in options for label in stored):
        st.session_state[picker_key] = ranked_labels[: min(3, len(options))]

    quick_add_col, _ = st.columns([1, 3])
    quick_add_n = quick_add_col.number_input("Quick-add top N by edge", min_value=2, max_value=min(8, len(options)), value=min(3, len(options)), key=f"{sport_key}_quick_add_n")
    if quick_add_col.button("Quick-add", key=f"{sport_key}_quick_add_button"):
        st.session_state[picker_key] = ranked_labels[:quick_add_n]

    chosen_labels = st.multiselect(
        "Legs",
        list(options),
        key=picker_key,
        help="Each leg uses the model's recommended side and its own price from the loaded odds.",
    )
    if len(chosen_labels) < 2:
        st.info("Pick at least 2 legs to evaluate a parlay.")
        return

    summary_rows = []
    legs = []
    for label in chosen_labels:
        row = options[label]
        side = row[side_key]
        if sport_key == "NFL":
            leg = make_leg(
                description=label, model_probability=row[f"model_probability_{side}"], price=row[f"{side}_price"],
                player_id=row["player_id"], team=row["team"], market=row["market"], side=side, confidence=row["confidence"],
            )
            summary_rows.append({"Leg": label, "Model prob.": row[f"model_probability_{side}"], "Edge": row["recommended_edge"], "Risk": row.get("risk_tier", "")})
        else:
            leg = nba_make_leg(
                description=label, model_probability=row[f"model_probability_{side}"], price=row[f"{side}_price"],
                player_id=row["player"], team=row["team"], market=row["category"], side=side, confidence=row.get("confidence_score", 70.0) / 100.0,
            )
            summary_rows.append({"Leg": label, "Model prob.": row[f"model_probability_{side}"], "EV / $100": row["recommended_priced_ev"], "Risk": row.get("risk_tier", "")})
        legs.append(leg)

    st.dataframe(pd.DataFrame(summary_rows), width="stretch", hide_index=True, column_config={"Model prob.": st.column_config.NumberColumn(format="%.1%")})

    result = (evaluate_parlay if sport_key == "NFL" else nba_evaluate_parlay)(legs)
    m1, m2, m3, m4 = st.columns(4)
    m1.metric("Adjusted hit probability", f"{result['adjusted_hit_probability']:.1%}")
    m2.metric("Payout / $100", f"${result['payout_per_100_stake']:,.2f}")
    m3.metric("Adjusted EV / $100", f"${result['adjusted_ev']:+,.2f}")
    m4.metric("Confidence", f"{result['confidence']:.0%}", help=f"Risk tier: {result['risk_tier']}")

    if result["correlations_detected"]:
        st.warning(f"Correlated legs detected -- hit probability adjusted from the naive {result['naive_hit_probability']:.1%} to {result['adjusted_hit_probability']:.1%}.")
        for finding in result["correlations_detected"]:
            leg_a, leg_b = finding["legs"]
            st.caption(f"- {legs[leg_a]['description']} + {legs[leg_b]['description']}: {finding['note']}")
    else:
        st.caption("No known correlation pattern detected between these legs.")


