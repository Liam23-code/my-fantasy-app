# Betting Engine: offline, deterministic fair-line analysis across five
# sections -- Player Props, Money Lines, Parlays, Player Comparison, and
# Cross-Sport Parlay -- for NFL, NBA, CFB, and CBB.
#
# Odds come from exactly two places, both offline, per sport: our own
# default file (generated by our own projection/team models) and an
# optional file you upload here (CSV, JSON, or delimited text), which
# overrides matching entries and leaves everything else untouched. Nothing
# on this page ever fetches a sportsbook, and nothing here places a bet --
# every number is a side-by-side comparison of our fair line against odds
# you supplied.
#
# All four sports share this page's UI and the same underlying contract
# (default file + upload, real per-game rates, disclosed "basis" on every
# generated line) but are evaluated by separate, sport-specific modules --
# see architecture.md / betting_engine.md / college_sports_betting.md for
# why the four engines aren't merged into one codebase.
#   NFL: fantasy_engine/betting/*        NBA: modules/nba_*.py
#   CFB: modules/cfb_*.py                CBB: modules/cbb_*.py
#
# CFB needs a College Football Data API key (set CFBD_API_KEY) for real
# data -- ships empty-by-design otherwise; see cfb_pipeline.md. CBB uses
# ESPN's public JSON API, no key required.
#
# Performance notes (see performance_notes.md): every real-data loader used
# here is TTL-cached at the module level, so the page-level @st.cache_data
# below is a second, Streamlit-specific layer on top of an already-cached
# call, not the only caching in play. Each sport's props/money-lines/
# parlays evaluation is computed once per render and reused across tabs.

