"""Shared data loaders and tab renderers for the seven betting pages (30-36).

Extracted from the former single-page ``30_Betting_Engine.py`` (now split
per sport -- see ui_betting_tabs.md) so the six sport pages and the
Cross-Sport Tools page import one copy of each loader/render function
instead of six near-duplicates. Behavior is unchanged from the original
page: same caching, same odds-source disclosure text, same table columns.

Odds come from exactly two places, both offline, per sport: our own
default file (generated by our own projection/team models, where one
exists) and an optional file you upload (CSV, JSON, or delimited text),
which overrides matching entries and leaves everything else untouched.
Nothing here ever fetches a sportsbook, and nothing here places a bet.

  NFL: fantasy_engine/betting/*        NBA: modules/nba_*.py
  CFB: modules/cfb_*.py                CBB: modules/cbb_*.py
  MLB: modules/mlb_*.py                NHL: modules/nhl_*.py

CFB needs a College Football Data API key (set CFBD_API_KEY) for real
data -- ships empty-by-design otherwise; see cfb_pipeline.md. CBB uses
ESPN's public JSON API, no key required. MLB and NHL ship empty by
design -- no live/scraped source was integrated for either this cycle
(see mlb_pipeline.md / nhl_pipeline.md); both work fully from an uploaded
file.
"""
