def load_nfl_evaluations(uploader_key: str) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, dict[str, float]]]:
    """Load NFL odds + real players, and return (prop_evaluations, game_evaluations, team_averages)."""
    source_season = upcoming_season() - 1
    with st.expander("Odds source", expanded=True):
        st.caption(
            "Default odds are generated by our own model from real per-game rates and real team scoring -- "
            "not fetched from any sportsbook. Upload a file below to override or add to them; only the "
            "entries your file names are replaced, everything else stays on our default."
        )
        uploaded_file = st.file_uploader(
            "Upload NFL odds (CSV, JSON, or text) to override our defaults",
            type=["csv", "json", "txt"],
            key=uploader_key,
        )
        try:
            odds = unified_odds(uploaded=uploaded_file if uploaded_file is not None else None)
        except OddsLoadError as error:
            st.error(f"Could not parse the uploaded odds file: {error}")
            odds = unified_odds()
        st.success(f"{len(odds['player_props'])} player props · {len(odds['games'])} games loaded.")

    players = _nfl_players(source_season)
    players_by_id = {str(player.get("player_id")): player for player in players}
    team_averages = _nfl_team_averages(source_season)
    prop_evaluations = evaluate_props(players_by_id, odds)
    game_evaluations = evaluate_games(odds, averages=team_averages)
    return prop_evaluations, game_evaluations, team_averages


def load_nba_evaluations(
    props_uploader_key: str, odds_uploader_key: str, *, max_players: int = 20
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    """Load NBA odds + real schedule, and return (priced_props, raw_props, game_evaluations, extra_context)."""
    nba_season = nba_latest_season()
    with st.expander("Odds source", expanded=True):
        st.caption(
            "Default NBA prop lines are generated by our own model from real per-game rates (see "
            "modules/nba_props_generator.py) -- not fetched from any sportsbook. Game odds have no fixed "
            "default (NBA's daily schedule changes every day); upload a file below, or rely on our fair "
            "lines alone, computed live from real team scoring."
        )
        uploaded_props_file = st.file_uploader(
            "Upload NBA player props (CSV, JSON, or text) to override our defaults",
            type=["csv", "json", "txt"],
            key=props_uploader_key,
        )
        uploaded_game_odds_file = st.file_uploader(
            "Upload NBA game odds (CSV, JSON, or text) -- moneyline / spread / total",
            type=["csv", "json", "txt"],
            key=odds_uploader_key,
        )

        with st.spinner("Loading odds sources..."):
            try:
                results = parse_uploads_concurrently(
                    {
                        "props": lambda: nba_unified_props(uploaded=uploaded_props_file if uploaded_props_file is not None else None),
                        "game_odds": lambda: unified_game_odds(uploaded=uploaded_game_odds_file if uploaded_game_odds_file is not None else None),
                    }
                )
                nba_props = results["props"]
                nba_game_odds = results["game_odds"]
            except GameOddsLoadError as error:
                st.error(f"Could not parse the uploaded game-odds file: {error}")
                nba_props = nba_unified_props(uploaded=uploaded_props_file if uploaded_props_file is not None else None)
                nba_game_odds = unified_game_odds()
        st.success(f"{len(nba_props)} player props · {len(nba_game_odds['games'])} game odds loaded.")

    todays_games = _nba_todays_games()
    if not todays_games:
        st.info("No real NBA games are scheduled today -- Money Lines and live-matchup Props below will be empty until game day.")

    recommendations: list[dict[str, Any]] = []
    if todays_games:
        with st.spinner("Scanning today's real matchups..."):
            recommendations = _nba_recommendations(nba_season, max_players)
    props_by_key = index_props_by_player_and_category(nba_props)
    priced = price_aware_evaluations(recommendations, props_by_key) if recommendations else []

    game_evaluations: list[dict[str, Any]] = []
    if todays_games:
        nba_averages = _nba_team_averages(nba_season)
        nba_vol = nba_volatility(nba_season)
        odds_by_matchup = index_by_matchup(nba_game_odds)
        game_evaluations = nba_evaluate_games(todays_games, averages=nba_averages, odds_by_matchup=odds_by_matchup, volatility=nba_vol)

    extra = {"season": nba_season, "todays_games": todays_games, "raw_props": nba_props}
    return priced, nba_props, game_evaluations, extra


def load_cfb_evaluations(
    props_uploader_key: str, odds_uploader_key: str, *, season: int, week: int
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    """Load CFB odds, and return (prop_evaluations, game_evaluations, extra_context). Real data needs CFBD_API_KEY."""
    import os

    has_key = bool(os.environ.get("CFBD_API_KEY"))
    with st.expander("Odds source", expanded=True):
        st.caption(
            "Default CFB prop lines need a College Football Data API key (set CFBD_API_KEY -- see "
            "cfb_pipeline.md) -- not fetched from any sportsbook. Upload a file below to use this tab "
            "without a key."
        )
        if not has_key:
            st.warning(
                "No CFBD_API_KEY is configured. Real per-game-rate props and team scoring are empty until "
                "one is set -- this tab still works fully with an uploaded props/odds file."
            )
        uploaded_props_file = st.file_uploader("Upload CFB player props (CSV, JSON, or text)", type=["csv", "json", "txt"], key=props_uploader_key)
        uploaded_game_odds_file = st.file_uploader("Upload CFB game odds (CSV, JSON, or text) -- moneyline / spread / total", type=["csv", "json", "txt"], key=odds_uploader_key)
        cfb_props = cfb_unified_props(uploaded=uploaded_props_file if uploaded_props_file is not None else None)
        try:
            cfb_game_odds = cfb_unified_game_odds(uploaded=uploaded_game_odds_file if uploaded_game_odds_file is not None else None)
        except CfbGameOddsLoadError as error:
            st.error(f"Could not parse the uploaded game-odds file: {error}")
            cfb_game_odds = cfb_unified_game_odds()
        st.success(f"{len(cfb_props)} player props · {len(cfb_game_odds['games'])} game odds loaded.")

    prop_evaluations = cfb_evaluate_props(cfb_props) if cfb_props else []

    games = _cfb_week_games(season, week) if has_key else []
    game_evaluations: list[dict[str, Any]] = []
    if games:
        averages = _cfb_team_averages(season)
        volatility = cfb_volatility_cached(season)
        odds_by_matchup = cfb_index_by_matchup(cfb_game_odds)
        game_evaluations = cfb_evaluate_games(games, averages=averages, odds_by_matchup=odds_by_matchup, volatility=volatility)

    return prop_evaluations, game_evaluations, {"has_key": has_key, "games": games, "raw_props": cfb_props}


