def _game_rows(game_evaluations: list[dict[str, Any]], *, include_ml_side: bool = False, include_total_side: bool = False) -> list[dict[str, Any]]:
    rows = []
    for game in game_evaluations:
        model = game["model"]
        moneyline = game.get("moneyline")
        total = game.get("total")
        row = {
            "Home": game["home_team"],
            "Away": game["away_team"],
            "Model spread (home)": model["spread"],
            "Model total": model["total"],
            "Home win prob.": model["home_win_probability"],
            "Fair home ML": model["fair_home_moneyline"],
            "Market home ML": moneyline["home_price"] if moneyline else None,
            "ML edge": moneyline["recommended_edge"] if moneyline else None,
        }
        if include_ml_side:
            row["ML side"] = moneyline["recommended_side"] if moneyline else None
        row["Total line"] = total["line"] if total else None
        row["Total edge"] = total["recommended_edge"] if total else None
        if include_total_side:
            row["Total side"] = total["recommended_side"] if total else None
        rows.append(row)
    return rows


